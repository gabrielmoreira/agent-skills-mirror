#!/usr/bin/env node
// One-time install of the render engine, macOS, Windows and Linux. Safe to run again: it only does what is missing.
//   node <skill>/engine/setup.mjs            install what is missing
//   node <skill>/engine/setup.mjs --check    report only, change nothing (exit 1 when something is missing)
// 1. Node 20+ and ffmpeg (never installed here: the command to run is printed)
// 2. the engine packages (npm install in engine/, about 15 MB)
// 3. a Chromium for the render: Chrome, Edge, Brave or Chromium already installed, else a headless shell in <skill>/.runtime
// 4. whisper.cpp (Homebrew on macOS, the official release on Windows) and its speech model (about 0.5 GB, once)
// 5. the 8 music beds (generated by code, assets/music/*.mp3) and the Noto icons (assets/icons/*.png)
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ENGINE = path.dirname(fileURLToPath(import.meta.url)), SKILL = path.dirname(ENGINE), RUNTIME = path.join(SKILL, '.runtime');
const CHECK = process.argv.includes('--check');
const IS_WIN = process.platform === 'win32', IS_MAC = process.platform === 'darwin';
const exists = f => { try { return fs.existsSync(f); } catch { return false; } };
const run = (cmd, args, opts = {}) => spawnSync(cmd, args, { stdio: 'inherit', shell: IS_WIN, ...opts });
const ok = (s) => console.log(`ok   ${s}`), todo = (s) => console.log(`todo ${s}`);
let missing = 0;
const t0 = Date.now();

// 1. Node and ffmpeg
const major = +process.versions.node.split('.')[0];
if (major < 20) { console.log(`Node ${process.versions.node} is too old: install Node 20 or newer (https://nodejs.org)`); process.exit(1); }
ok(`node ${process.versions.node}`);
const ffmpegOk = () => spawnSync(process.env.FFMPEG_PATH || 'ffmpeg', ['-version'], { stdio: 'ignore' }).status === 0;
if (!ffmpegOk()) {
  console.log(`ffmpeg is missing. Install it, open a new terminal, then run this again:\n  ${IS_MAC ? 'brew install ffmpeg' : IS_WIN ? 'winget install Gyan.FFmpeg' : 'sudo apt install ffmpeg'}`);
  process.exit(1);
}
ok('ffmpeg');

// 2. engine packages
if (!exists(path.join(ENGINE, 'node_modules', 'playwright-core'))) {
  missing++;
  if (CHECK) todo('engine packages (npm install in engine/)');
  else {
    console.log('installing the engine packages (about 15 MB)...');
    if (run('npm', ['install', '--no-audit', '--no-fund', '--loglevel', 'error'], { cwd: ENGINE }).status) process.exit(1);
    missing--; ok('engine packages');
  }
} else ok('engine packages');

// 3. a Chromium (platform.mjs finds the installed browser, else the headless shell under .runtime/browsers)
const ensureRuntime = () => { fs.mkdirSync(RUNTIME, { recursive: true }); if (!exists(path.join(RUNTIME, 'runtime.json'))) fs.writeFileSync(path.join(RUNTIME, 'runtime.json'), '{}\n'); };
let { CHROME } = await import('./platform.mjs');
if (!exists(CHROME)) {
  missing++;
  if (CHECK) todo('a Chromium for the render (Chrome, Edge, or the headless shell)');
  else {
    console.log('no Chrome found: installing a headless Chromium for the render (about 100 MB)...');
    ensureRuntime();
    const r = run('npx', ['playwright-core', 'install', 'chromium-headless-shell'], { cwd: ENGINE, env: { ...process.env, PLAYWRIGHT_BROWSERS_PATH: path.join(RUNTIME, 'browsers') } });
    if (r.status) process.exit(1);
    ({ CHROME } = await import(`./platform.mjs?again=${Date.now()}`));
    if (!exists(CHROME)) { console.log('the headless Chromium did not install: install Google Chrome, then run this again'); process.exit(1); }
    missing--; ok(`chromium: ${CHROME}`);
  }
} else ok(`chromium: ${CHROME}`);

// 4. whisper.cpp and its model
const W = await import('./whisper.mjs');
if (!W.findWhisper()) {
  missing++;
  if (CHECK) todo('whisper.cpp (local transcription)');
  else if (IS_MAC) {
    if (spawnSync('brew', ['--version'], { stdio: 'ignore' }).status) { console.log('whisper.cpp needs Homebrew (https://brew.sh), then: brew install whisper-cpp'); process.exit(1); }
    console.log('installing whisper.cpp with Homebrew...');
    if (run('brew', ['install', 'whisper-cpp']).status) process.exit(1);
    missing--;
  } else if (IS_WIN) {
    console.log('downloading whisper.cpp for Windows (official release)...');
    ensureRuntime();
    const dir = path.join(RUNTIME, 'whisper'), zip = path.join(RUNTIME, 'whisper-bin-x64.zip');
    fs.mkdirSync(dir, { recursive: true });
    const r = await fetch('https://github.com/ggml-org/whisper.cpp/releases/latest/download/whisper-bin-x64.zip');
    if (!r.ok) { console.log(`download failed (HTTP ${r.status}): get whisper-bin-x64.zip from https://github.com/ggml-org/whisper.cpp/releases and unzip it into ${dir}`); process.exit(1); }
    fs.writeFileSync(zip, Buffer.from(await r.arrayBuffer()));
    if (spawnSync('tar', ['-xf', zip, '-C', dir], { stdio: 'inherit' }).status) process.exit(1);
    fs.unlinkSync(zip);
    missing--;
  } else { console.log('whisper.cpp: build it (https://github.com/ggml-org/whisper.cpp) and put whisper-cli on the PATH, or set WHISPER_CLI'); process.exit(1); }
  if (!CHECK) { if (!W.findWhisper()) { console.log('whisper-cli still not found: open a new terminal and run this again'); process.exit(1); } ok(`whisper.cpp: ${W.findWhisper()}`); }
} else ok(`whisper.cpp: ${W.findWhisper()}`);
if (!exists(W.modelPath())) {
  missing++;
  if (CHECK) todo(`speech model ${path.basename(W.modelPath())} (about 0.5 GB)`);
  else { await W.ensureModel(); missing--; ok(`speech model ${path.basename(W.modelPath())}`); }
} else ok(`speech model ${path.basename(W.modelPath())}`);

// 5. music beds and icons, both generated on this computer
const env = { ...process.env, CHROME_PATH: process.env.CHROME_PATH || CHROME };
const beds = JSON.parse(fs.readFileSync(path.join(SKILL, 'assets/music/tracks.json'), 'utf8'));
const ids = (Array.isArray(beds) ? beds : beds.tracks || []).map(t => t.id).filter(Boolean);
const noBed = ids.filter(id => !exists(path.join(SKILL, 'assets/music', `${id}.mp3`)));
if (noBed.length) {
  missing++;
  if (CHECK) todo(`music beds (${noBed.length} to generate)`);
  else {
    console.log(`generating ${noBed.length} music beds (code, no download, about a minute)...`);
    if (run(process.execPath, [path.join(ENGINE, 'music.mjs')], { cwd: ENGINE, shell: false }).status) process.exit(1);
    missing--; ok('music beds');
  }
} else ok(`music beds (${ids.length})`);
if (!exists(path.join(SKILL, 'assets/icons/check.png'))) {
  missing++;
  if (CHECK) todo('icons (Google Noto, drawn from assets/icons/svg)');
  else {
    console.log('drawing the icons (Google Noto emoji, about 30 s)...');
    if (run(process.execPath, [path.join(SKILL, 'assets/icons/build-icons.mjs')], { cwd: ENGINE, env, shell: false }).status) process.exit(1);
    missing--; ok('icons');
  }
} else ok('icons');

console.log(missing ? `${missing} thing(s) to install: run node ${path.relative(process.cwd(), fileURLToPath(import.meta.url))}` : `engine ready (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
process.exit(missing ? 1 : 0);
